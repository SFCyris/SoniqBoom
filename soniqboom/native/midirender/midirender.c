/* SPDX-FileCopyrightText: 2026 S.F. Cyris
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * midirender — render a song of the MIDI family through an emulated
 * synthesizer to a 16-bit stereo WAV: OPL3 FM (libADLMIDI), OPN2 FM
 * (libOPNMIDI) or a Roland MT-32 / CM-32L (libmt32emu, munt) with the ROMs
 * the user supplies.  Standard MIDI files (.mid, RIFF .rmi, .kar) and the
 * game formats libADLMIDI's sequencer reads: AIL XMIDI (.xmi), DMX MUS
 * (Doom), HMI / HMP (Human Machine Interfaces), GMF and KLM (KLM: OPL3 only —
 * it holds OPL register writes, not MIDI).
 *
 *   midirender [-s opl3|opn2|mt32] [-b bank] [-e emulator] [-c chips]
 *              [-n song] [-r rate] [-m max_seconds] [-f fade_ms]
 *              [-R rom_dir] [-M machine] FILE OUT.wav
 *   midirender -i [-n song] FILE
 *   midirender -L
 *   midirender -V rom_dir [-M machine]
 *   midirender --version
 *
 * The song plays once to its end (loop points are not repeated), then the
 * synthesizer's release and reverb tail plays on until it is silent (at
 * most TAIL_MAX_S); a song longer than max_seconds (default 1800) is cut
 * there, its last fade_ms (default 8000) fading out.  -n picks a song of a
 * file that holds several (XMI; 0-based).
 *   opl3: -b is an embedded bank — its number (default 0) or the start of its
 *         name ("AIL (The Fat Man", as -L prints it) — or a .wopl file; -e the
 *         OPL3 emulator (default 0, Nuked OPL3 — libADLMIDI's
 *         ADLMIDI_EMU_* numbers); -c the number of emulated chips (1-100,
 *         default 2).
 *   opn2: -b is a .wopn file (default: the bank compiled in, Wohlstand's
 *         xg.wopn); -e the OPN2 emulator (default 1, Nuked OPN2 YM3438 —
 *         libOPNMIDI's OPNMIDI_EMU_* numbers); -c the chips (default 2).
 *   mt32: -R the folder holding the control and PCM ROM images (full or
 *         partial images, any file names — libmt32emu identifies them by
 *         content); -M a machine id ("mt32_1_07", "cm32l_1_02" …; default:
 *         the first of MACHINE_ORDER the folder has both ROMs for).  The
 *         MIDI events come from libADLMIDI's sequencer (so every format it
 *         reads plays on the MT-32, SysEx included).
 * The WAV is written as it renders (a 44-byte header first, its sizes
 * patched at the end), flushed after every block, so a reader can follow it.
 * -i loads the song and prints "seconds=" (its length — the render adds the
 * tail), "loop_start=", "loop_end=" (-1 without a loop), "songs=", "title="
 * and "copyright=".  -L prints "synths=" (the synthesizers compiled in) and
 * the embedded OPL3 banks as "bank=N name".  -V prints "machine=",
 * "control=" and "pcm=" (the ROMs libmt32emu identified) and exits 0, or
 * "error=" and exits 3.
 * Exit status: 0 with audio written, 1 on a file that can't be loaded, a
 * song that played nothing or a failed write (a partial WAV may be left), 2
 * on usage, 3 when the MT-32 ROMs are missing or not recognised, 4 for a
 * synthesizer not compiled in. */

