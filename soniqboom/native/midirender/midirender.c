/* ── The output ──────────────────────────────────────────────────────────── */

typedef struct {
  FILE *fp;
  long rate;
  uint64_t frames;               /* frames written */
  uint64_t max_frames;           /* the cut (0: none) */
  uint64_t fade_frames;          /* the fade before the cut */
  uint64_t quiet_run;            /* trailing frames at most SILENCE_PEAK */
  int failed;
} Out;

/* Write ``n`` frames of ``buf`` (interleaved s16 stereo), faded out over the
 * last ``fade_frames`` before ``max_frames`` and cut there.  Returns the
 * frames written; 0 once the cut is reached. */
static long out_write(Out *o, int16_t *buf, long n) {
  if (o->failed || n <= 0)
    return 0;
  if (o->max_frames && o->frames + (uint64_t)n > o->max_frames)
    n = (long)(o->max_frames - o->frames);
  if (n <= 0)
    return 0;
  if (o->max_frames && o->fade_frames) {
    uint64_t fade_from = o->max_frames > o->fade_frames ? o->max_frames - o->fade_frames : 0;
    for (long i = 0; i < n; i++) {
      uint64_t f = o->frames + (uint64_t)i;
      if (f >= fade_from) {
        double g = (double)(o->max_frames - f) / (double)o->fade_frames;
        buf[2 * i] = (int16_t)lrint(buf[2 * i] * g);
        buf[2 * i + 1] = (int16_t)lrint(buf[2 * i + 1] * g);
      }
    }
  }
  for (long i = 0; i < n; i++) {
    if (abs(buf[2 * i]) <= SILENCE_PEAK && abs(buf[2 * i + 1]) <= SILENCE_PEAK)
      o->quiet_run++;
    else
      o->quiet_run = 0;
  }
  if (o->fp) {
    unsigned char le[BLOCK_FRAMES * 4];
    long done = 0;
    while (done < n) {
      long k = n - done > BLOCK_FRAMES ? BLOCK_FRAMES : n - done;
      for (long i = 0; i < k * 2; i++)
        put16(le + 2 * i, (uint16_t)buf[2 * (done) + i]);
      if (fwrite(le, 1, (size_t)(k * 4), o->fp) != (size_t)(k * 4)) {
        o->failed = 1;
        return 0;
      }
      done += k;
    }
    if (fflush(o->fp) != 0) {
      o->failed = 1;
      return 0;
    }
  }
  o->frames += (uint64_t)n;
  return n;
}

static int out_cut(const Out *o) {
  return o->failed || (o->max_frames && o->frames >= o->max_frames);
}

static int out_tail_done(const Out *o, uint64_t tail_frames) {
  return out_cut(o) || tail_frames >= (uint64_t)(TAIL_MAX_S * o->rate)
         || o->quiet_run >= (uint64_t)(TAIL_SILENT_S * o->rate);
}

