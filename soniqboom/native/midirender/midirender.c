/* ── Rendering ───────────────────────────────────────────────────────────── */

static int finish(Out *o, const char *out_path, int had_audio) {
  if (!o->fp)
    return o->failed ? 1 : 0;
  unsigned char h[44];
  uint64_t bytes = o->frames * 4;
  wav_header(h, (uint32_t)o->rate, (uint32_t)bytes);
  if (!o->failed && (fseek(o->fp, 0, SEEK_SET) != 0 || fwrite(h, 1, sizeof h, o->fp) != sizeof h))
    o->failed = 1;
  if (fclose(o->fp) != 0)
    o->failed = 1;
  o->fp = NULL;
  if (o->failed) {
    fprintf(stderr, "midirender: write failed: %s\n", out_path);
    return 1;
  }
  if (!had_audio) {
    fprintf(stderr, "midirender: the song played nothing\n");
    return 1;
  }
  return 0;
}

static int load_song(struct ADL_MIDIPlayer *adl, const char *in, int song) {
  if (song >= 0)
    adl_selectSongNum(adl, song);
  if (adl_openFile(adl, in) != 0) {
    fprintf(stderr, "midirender: can't load %s: %s\n", in, adl_errorInfo(adl));
    return 1;
  }
  return 0;
}

static int render_opl3(const char *in, Out *o, const char *bank, int emu, int chips, int song) {
  struct ADL_MIDIPlayer *adl = adl_init(o->rate);
  if (!adl) {
    fprintf(stderr, "midirender: %s\n", adl_errorString());
    return 1;
  }
  int rc = 1;
  char *end = NULL;
  long num = bank ? strtol(bank, &end, 10) : 0;
  struct stat st;
  if (bank && *bank && end && *end == '\0') {
    if (num < 0 || num >= adl_getBanksCount() || adl_setBank(adl, (int)num) != 0) {
      fprintf(stderr, "midirender: no OPL3 bank %ld\n", num);
      goto done;
    }
  } else if (bank && stat(bank, &st) == 0) {
    if (adl_openBankFile(adl, bank) != 0) {
      fprintf(stderr, "midirender: can't load the bank %s: %s\n", bank, adl_errorInfo(adl));
      goto done;
    }
  } else if (bank) {
    /* (an embedded bank by the start of its name) */
    int n = adl_getBanksCount(), found = -1;
    const char *const *names = adl_getBankNames();
    for (int i = 0; i < n && names && found < 0; i++)
      if (names[i] && strncmp(names[i], bank, strlen(bank)) == 0)
        found = i;
    if (found < 0 || adl_setBank(adl, found) != 0) {
      fprintf(stderr, "midirender: no OPL3 bank named %s\n", bank);
      goto done;
    }
  }
  if (adl_switchEmulator(adl, emu) != 0) {
    fprintf(stderr, "midirender: no OPL3 emulator %d\n", emu);
    goto done;
  }
  adl_setNumChips(adl, chips);
  adl_setLoopEnabled(adl, 0);
  adl_setSoftPanEnabled(adl, 1);
  if (load_song(adl, in, song) != 0)
    goto done;
  int16_t buf[BLOCK_FRAMES * 2];
  int heard = 0;
  while (!adl_atEnd(adl) && !out_cut(o)) {
    int got = adl_play(adl, BLOCK_FRAMES * 2, buf);
    if (got <= 0)
      break;
    for (int i = 0; i < got && !heard; i++)
      heard = buf[i] != 0;
    out_write(o, buf, got / 2);
  }
  uint64_t tail = 0;
  o->quiet_run = 0;
  while (!out_tail_done(o, tail)) {
    int got = adl_generate(adl, BLOCK_FRAMES * 2, buf);
    if (got <= 0)
      break;
    tail += (uint64_t)out_write(o, buf, got / 2);
  }
  rc = heard ? 0 : 2;
done:
  adl_close(adl);
  return rc;
}

