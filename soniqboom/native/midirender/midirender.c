#define BLOCK_FRAMES 1024
#define TAIL_MAX_S 6.0
#define TAIL_SILENT_S 0.25        /* this much at most SILENCE_PEAK ends the tail */
#define SILENCE_PEAK 4
#define ROM_MAX_BYTES (2L * 1024 * 1024)
#define ROM_MAX_FILES 256

/* The machines tried in turn when -M is not given: an MT-32 first (most
 * game music written for one plays as meant on it): control ROM 1.07 to
 * 1.04, then the 2.x revisions; then the CM-32L / CM-32LN. */
static const char *const MACHINE_ORDER[] = {
  "mt32_1_07", "mt32_1_06", "mt32_1_05", "mt32_1_04", "mt32_bluer",
  "mt32_2_07", "mt32_2_06", "mt32_2_04", "mt32_2_03",
  "cm32l_1_02", "cm32l_1_00", "cm32ln_1_00", NULL
};

static void put32(unsigned char *p, uint32_t v) {
  p[0] = v & 0xff; p[1] = (v >> 8) & 0xff; p[2] = (v >> 16) & 0xff; p[3] = (v >> 24) & 0xff;
}

static void put16(unsigned char *p, uint16_t v) {
  p[0] = v & 0xff; p[1] = (v >> 8) & 0xff;
}

static void wav_header(unsigned char *h, uint32_t rate, uint32_t data_bytes) {
  memcpy(h, "RIFF", 4);
  put32(h + 4, 36 + data_bytes);
  memcpy(h + 8, "WAVEfmt ", 8);
  put32(h + 16, 16);
  put16(h + 20, 1);              /* PCM */
  put16(h + 22, 2);              /* stereo */
  put32(h + 24, rate);
  put32(h + 28, rate * 4);       /* bytes per second */
  put16(h + 32, 4);              /* block align: 2 channels x 16 bits */
  put16(h + 34, 16);
  memcpy(h + 36, "data", 4);
  put32(h + 40, data_bytes);
}

