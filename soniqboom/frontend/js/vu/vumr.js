/**
 * vu/vumr.js — the per-voice VU meter's data, shared by the desktop player bar
 * (app.js) and the phone's Now Playing (mobile/views/np_visuals.js).  No DOM.
 *
 * A tracker / chip / Amiga / Atari / PSF tune has a per-voice VU sidecar
 * (VUMR v1, docs/vu-cache-format.md) at GET /api/tracks/{id}/vu: one level per
 * voice per frame, indexed by the playback time.  Until it exists (SID: the
 * server's background renders; Amiga: a pass the first ask starts, once the
 * track has played AMIGA_VU_SETTLE_S) the meter is an honest FFT spectrum, and
 * the caller asks again on the SID / Amiga ladder.
 *
 *   parseVUMR(buf)                 → {channels, rateHz, frames, pan, samples} | null
 *   createVumrFetcher()            → {fetch(id, subsong, {start}), abort()}
 *   vuEligible(track)              → whether the track gets the per-voice meter
 *   vuKeyOf(track)                 → "<id>:<subsong>"
 *   vuLabelStep(channels, width)   → 1 / 2 / 4 / 8 / 16: every how many voices keep their number
 *   vumrLevelsAt(vumr, t, out, n)  → out[0…n) = the voices' levels at t seconds (0…1)
 *   fftColumnLevels(bins, n, out)  → out[0…n) = byte-spectrum bins averaged into n columns
 *   vuFallbackText(format, reason, isAdmin) → the spectrum's caption when no voices come
 */
import { TRACKER_FORMAT_NAMES, CHIP_FORMAT_NAMES, ATARI_FORMAT_NAMES,
         PSF_FORMAT_NAMES, isUadeAmigaTrack } from '../utils.js';

export const VUMR_MAX_CHANNELS = 32;

// FFT fallback column count.  Fixed regardless of track.channels — the
// fallback is an honest spectrum analyzer, not a faux per-voice meter.
export const FFT_FALLBACK_BARS = 32;

// SID's per-voice sidecar is generated by 3 background sidplayfp renders on the
// first play, so /vu answers 204 at track-load: ask again on this schedule
// (cumulative ~3/8/16/28/44/66/96/141/201/261 s — the pass is serialised on the
// server, so a few queued tunes can push it minutes out).  See app.js.
export const SID_VU_RETRY_MS = [3000, 5000, 8000, 12000, 16000, 22000, 30000, 45000, 60000, 60000];
// Amiga modules: the sidecar lands some 5–12 s after the first ask.  Ask every
// 3 s through that window, then back off — never beyond 15 s: the server drops
// a queued pass that has not been polled for ``_UADE_VU_POLL_FRESH_S`` (20 s,
// api/stream.py; tests/js/frontend_contracts.test.mjs checks the two against
// each other).
export const AMIGA_VU_RETRY_MS = [3000, 3000, 3000, 3000, 3000, 4000, 5000, 8000, 12000,
                                  15000, 15000, 15000, 15000, 15000, 15000, 15000, 15000];
// The Amiga pass is asked for only once the track has played this long (the
// player's next-track prewarm settle): a track skipped sooner never costs it.
export const AMIGA_VU_SETTLE_S = 3;
export const AMIGA_VU_SETTLE_POLL_MS = 1000;
export const AMIGA_VU_SETTLE_MAX_WAITS = 3600;   // an hour paused in the first seconds

// Trackers get per-voice VUMR; SID + libgme console chiptunes + AdPlug AdLib /
// OPL render fine but may have no sidecar, so they fall back to the spectrum.
const _VU_FORMATS = new Set([...TRACKER_FORMAT_NAMES, 'SID', ...CHIP_FORMAT_NAMES]);

/** Eligibility for the per-voice meter: the static tracker / SID / chip names
 *  plus the families whose names can't live in a static set — the exotic uade
 *  Amiga players (dynamic names; the genre pair is the signal), Atari ST
 *  (SNDH / YM / SC68) and the PSF consoles.  Every other track is ordinary
 *  audio (the needle meters). */
export function vuEligible(track) {
  const primary = String(track?.format || '').split('/')[0].trim();
  return _VU_FORMATS.has(primary)
      || isUadeAmigaTrack(track)
      || ATARI_FORMAT_NAMES.has(primary)
      || PSF_FORMAT_NAMES.has(primary);
}

export function vuKeyOf(track) {
  if (!track) return '';
  const ss = Number.isInteger(track.subsong) ? track.subsong : 0;
  return `${track.id}:${ss}`;
}

// VUMR binary layout (docs/vu-cache-format.md):
//   0..4   "VUMR"
//   4      version (0x01)
//   5      channels N (1..32)
//   6      flags  (reserved)
//   7      reserved
//   8..12  sample_rate_hz (uint32 LE)
//   12..16 frame_count    (uint32 LE)
//   16..16+N        pan per channel (uint8: 0=center, 1=left, 2=right)
//   16+N..end       mono amplitude (frames * channels * uint8)
export function parseVUMR(arrayBuf) {
  if (!arrayBuf || arrayBuf.byteLength < 16) return null;
  const dv = new DataView(arrayBuf);
  const magic = String.fromCharCode(dv.getUint8(0), dv.getUint8(1), dv.getUint8(2), dv.getUint8(3));
  if (magic !== 'VUMR') return null;
  if (dv.getUint8(4) !== 1) return null;
  const channels = dv.getUint8(5);
  const rateHz   = dv.getUint32(8, true);
  const frames   = dv.getUint32(12, true);
  if (channels < 1 || channels > VUMR_MAX_CHANNELS) return null;
  if (rateHz < 1 || rateHz > 240) return null;
  const headerSize = 16 + channels;
  if (arrayBuf.byteLength < headerSize + frames * channels) return null;
  const pan     = new Uint8Array(arrayBuf, 16, channels);
  const samples = new Uint8Array(arrayBuf, headerSize, frames * channels);
  return { channels, rateHz, frames, pan, samples };
}

/** A /vu reader with its own in-flight slot: a new ask aborts the previous one
 *  (its late answer can't land on a track already left), ``abort()`` frees it.
 *
 *  ``fetch(trackId, subsong, {start})`` resolves to the parsed sidecar; to
 *  ``{unavailable: true, reason}`` when the server says none is coming (a 204
 *  with ``X-VU-Unavailable``: 'off' | 'unsupported' | 'skipped'); or to null —
 *  not yet / try later (a plain 204, an error, an abort).  ``subsong``: the
 *  playing tune's wire number (a plain play of the file — none — is its default
 *  tune).  ``start: false`` answers from the cache only: a miss must not start
 *  the Amiga per-voice pass (a second full uade render). */
export function createVumrFetcher() {
  let ctl = null;
  function abort() {
    if (ctl) { try { ctl.abort(); } catch (_) {} ctl = null; }
  }
  async function fetchVu(trackId, subsong, { start = true } = {}) {
    if (!trackId) return null;
    abort();
    const mine = (typeof AbortController === 'function') ? new AbortController() : null;
    ctl = mine;
    try {
      const qs = new URLSearchParams();
      if (Number.isInteger(subsong)) qs.set('subsong', String(subsong));
      if (!start) qs.set('start', '0');
      const q = qs.toString();
      const res = await fetch(`/api/tracks/${encodeURIComponent(trackId)}/vu${q ? `?${q}` : ''}`,
                              mine ? { credentials: 'include', signal: mine.signal }
                                   : { credentials: 'include' });
      if (!res.ok || res.status === 204) {
        const reason = res.headers.get('X-VU-Unavailable');
        return reason ? { unavailable: true, reason: reason.trim().toLowerCase() } : null;
      }
      return parseVUMR(await res.arrayBuffer());
    } catch (_) {
      return null;                                  // aborted or failed: "not yet"
    } finally {
      if (ctl === mine) ctl = null;
    }
  }
  return { fetch: fetchVu, abort, get busy() { return !!ctl; } };
}

/** Channel numbers that don't fit their column (many voices, a narrow meter)
 *  thin out to every 2nd / 4th / 8th / 16th voice, the others marked with a dot
 *  — a mixing desk's scale; above 48 voices never closer than every 8th.
 *  ``digitPx`` is a digit's width at the label's font size. */
export function vuLabelStep(channels, hostWidth, digitPx = 6) {
  const n = Math.max(1, channels | 0);
  const colW = hostWidth / n;
  const needW = digitPx * String(n).length + 8;      // the digits + a gap
  let step = [1, 2, 4, 8, 16].find(k => colW * k >= needW) || 16;
  if (n > 48) step = Math.max(step, 8);
  return step;
}

/** The voices' levels at ``t`` seconds into the tune, 0…1, into ``out`` —
 *  with the meter's mild gamma (0.7: quiet hits register without compressing
 *  the loud end, as the FFT columns). */
export function vumrLevelsAt(vumr, t, out, n = vumr.channels) {
  if (!(vumr.frames >= 1)) { for (let ch = 0; ch < n; ch++) out[ch] = 0; return out; }   // (a streaming render's first partial)
  const frameIdx = Math.min(vumr.frames - 1, Math.max(0, Math.floor((t || 0) * vumr.rateHz)));
  const base = frameIdx * vumr.channels;
  const m = Math.min(n, vumr.channels);
  for (let ch = 0; ch < m; ch++) out[ch] = Math.pow(vumr.samples[base + ch] / 255, 0.7);
  for (let ch = m; ch < n; ch++) out[ch] = 0;
  return out;
}

/** A byte frequency spectrum (AnalyserNode.getByteFrequencyData) averaged
 *  into ``n`` equal columns, 0…1, gamma 0.7, into ``out``. */
export function fftColumnLevels(bins, n, out) {
  const bufLen = bins.length;
  const per = Math.max(1, Math.floor(bufLen / n));
  for (let ch = 0; ch < n; ch++) {
    const start = ch * per;
    let sum = 0;
    for (let i = start; i < start + per && i < bufLen; i++) sum += bins[i];
    out[ch] = Math.pow(sum / per / 255, 0.7);
  }
  return out;
}

/** The spectrum's caption when no per-voice meters will come: why, when the
 *  server said (``X-VU-Unavailable``), else "not available for <format>". */
export function vuFallbackText(format, reason, isAdmin = false) {
  if (reason === 'off') {
    return isAdmin
      ? 'Spectrum — per-voice meters are turned off (gear → Renderers → Playback preparation)'
      : 'Spectrum — per-voice meters are turned off on this server';
  }
  if (reason === 'skipped') return 'Spectrum — per-voice meters not available for this tune';
  if (reason === 'unsupported') return 'Spectrum — per-voice meters not available on this server';
  return `Spectrum — per-voice meters not available for ${format}`;
}
